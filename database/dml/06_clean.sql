ALTER SESSION SET CONTAINER = b_20251sen190_kevin_api_db;
SET SERVEROUTPUT ON

CREATE TABLE stg_web_traffic_clean (
    clean_id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    http_method         VARCHAR2(10)  NOT NULL,
    endpoint_path       VARCHAR2(500) NOT NULL,
    path_length         NUMBER(6)     NOT NULL,
    body_length         NUMBER(10)    NOT NULL,
    url_single_q        NUMBER(5)     NOT NULL,
    url_double_q        NUMBER(5)     NOT NULL,
    url_dashes          NUMBER(5)     NOT NULL,
    url_braces          NUMBER(5)     NOT NULL,
    url_spaces          NUMBER(5)     NOT NULL,
    url_percentages     NUMBER(5)     NOT NULL,
    url_semicolons      NUMBER(5)     NOT NULL,
    url_angle_brackets  NUMBER(5)     NOT NULL,
    url_special_chars   NUMBER(5)     NOT NULL,
    url_badwords        NUMBER(5)     NOT NULL,
    body_single_q       NUMBER(5)     NOT NULL,
    body_double_q       NUMBER(5)     NOT NULL,
    body_dashes         NUMBER(5)     NOT NULL,
    body_braces         NUMBER(5)     NOT NULL,
    body_spaces         NUMBER(5)     NOT NULL,
    body_percentages    NUMBER(5)     NOT NULL,
    body_semicolons     NUMBER(5)     NOT NULL,
    body_angle_brackets NUMBER(5)     NOT NULL,
    body_special_chars  NUMBER(5)     NOT NULL,
    body_badwords       NUMBER(5)     NOT NULL,
    actual_class        NUMBER(1)     NOT NULL,
    model_prediction    NUMBER(1)     NOT NULL
) TABLESPACE apithreat_data;

DECLARE
    v_total_raw       NUMBER;
    v_trimmed         NUMBER;
    v_zero_methods    NUMBER;
    v_zero_paths      NUMBER;
    v_pii_masked      NUMBER;
    v_duplicates      NUMBER;
    v_clean_count     NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_total_raw FROM stg_web_traffic_raw;

    UPDATE stg_web_traffic_raw
    SET raw_method     = TRIM(REPLACE(raw_method, CHR(13), '')),
        raw_path       = TRIM(REPLACE(raw_path, CHR(13), '')),
        raw_prediction = TRIM(REPLACE(raw_prediction, CHR(13), ''));
    v_trimmed := SQL%ROWCOUNT;

    UPDATE stg_web_traffic_raw
    SET raw_method = CASE WHEN raw_method = '0' THEN 'UNKNOWN' ELSE UPPER(raw_method) END
    WHERE raw_method = '0' OR raw_method <> UPPER(raw_method);
    v_zero_methods := SQL%ROWCOUNT;

    UPDATE stg_web_traffic_raw
    SET raw_path = '/unknown'
    WHERE raw_path = '0';
    v_zero_paths := SQL%ROWCOUNT;

    UPDATE stg_web_traffic_raw
    SET raw_path = REGEXP_REPLACE(raw_path, 'JohnSmith', 'USER_REDACTED', 1, 0, 'i')
    WHERE REGEXP_LIKE(raw_path, 'JohnSmith', 'i');
    v_pii_masked := SQL%ROWCOUNT;

    INSERT INTO stg_web_traffic_clean (
        http_method, endpoint_path, path_length, body_length,
        url_single_q, url_double_q, url_dashes, url_braces, url_spaces,
        url_percentages, url_semicolons, url_angle_brackets, url_special_chars, url_badwords,
        body_single_q, body_double_q, body_dashes, body_braces, body_spaces,
        body_percentages, body_semicolons, body_angle_brackets, body_special_chars, body_badwords,
        actual_class, model_prediction
    )
    SELECT DISTINCT
        raw_method,
        raw_path,
        TO_NUMBER(TRIM(url_path_length)),
        TO_NUMBER(TRIM(url_body_length)),
        TO_NUMBER(TRIM(url_single_q)),
        TO_NUMBER(TRIM(url_double_q)),
        TO_NUMBER(TRIM(url_dashes)),
        TO_NUMBER(TRIM(url_braces)),
        TO_NUMBER(TRIM(url_spaces)),
        TO_NUMBER(TRIM(url_percentages)),
        TO_NUMBER(TRIM(url_semicolons)),
        TO_NUMBER(TRIM(url_angle_brackets)),
        TO_NUMBER(TRIM(url_special_chars)),
        TO_NUMBER(TRIM(url_badwords)),
        TO_NUMBER(TRIM(body_single_q)),
        TO_NUMBER(TRIM(body_double_q)),
        TO_NUMBER(TRIM(body_dashes)),
        TO_NUMBER(TRIM(body_braces)),
        TO_NUMBER(TRIM(body_spaces)),
        TO_NUMBER(TRIM(body_percentages)),
        TO_NUMBER(TRIM(body_semicolons)),
        TO_NUMBER(TRIM(body_angle_brackets)),
        TO_NUMBER(TRIM(body_special_chars)),
        TO_NUMBER(TRIM(body_badwords)),
        TO_NUMBER(TRIM(raw_class)),
        TO_NUMBER(TRIM(raw_prediction))
    FROM stg_web_traffic_raw;

    v_clean_count := SQL%ROWCOUNT;
    v_duplicates  := v_total_raw - v_clean_count;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('=== PHASE IV DATA CLEANING AUDIT REPORT ===');
    DBMS_OUTPUT.PUT_LINE('Raw staged rows loaded              : ' || v_total_raw);
    DBMS_OUTPUT.PUT_LINE('Step 1 - Rows trimmed/sanitized     : ' || v_trimmed);
    DBMS_OUTPUT.PUT_LINE('Step 2 - Method ''0'' -> ''UNKNOWN''    : ' || v_zero_methods);
    DBMS_OUTPUT.PUT_LINE('Step 3 - Path ''0'' -> ''/unknown''     : ' || v_zero_paths);
    DBMS_OUTPUT.PUT_LINE('Step 4 - PII (JohnSmith) masked     : ' || v_pii_masked);
    DBMS_OUTPUT.PUT_LINE('Step 5 - Exact duplicates removed   : ' || v_duplicates);
    DBMS_OUTPUT.PUT_LINE('Final clean unique rows ready       : ' || v_clean_count);
END;
