ALTER SESSION SET CONTAINER = b_20251sen190_kevin_api_db;

BEGIN
  FOR t IN (SELECT table_name FROM user_tables
            WHERE table_name IN ('IP_QUARANTINE_LIST', 'SECURITY_THREATS',
                                 'REQUEST_LEXICAL_METRICS', 'REQUEST_LOGS',
                                 'API_ENDPOINTS')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- 1. Parent Table: API_ENDPOINTS
CREATE TABLE api_endpoints (
    endpoint_id       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT nn_api_endpoints_id NOT NULL,
    http_method       VARCHAR2(10)  DEFAULT 'UNKNOWN' CONSTRAINT nn_api_endpoints_method NOT NULL,
    endpoint_path     VARCHAR2(500) CONSTRAINT nn_api_endpoints_path NOT NULL,
    path_length       NUMBER(6)     DEFAULT 0 CONSTRAINT nn_api_endpoints_path_len NOT NULL,
    sensitivity_level VARCHAR2(15)  DEFAULT 'MEDIUM' CONSTRAINT nn_api_endpoints_sens NOT NULL,
    created_at        TIMESTAMP     DEFAULT SYSTIMESTAMP CONSTRAINT nn_api_endpoints_created NOT NULL
) TABLESPACE apithreat_data;

-- 2. Child Table: REQUEST_LOGS
CREATE TABLE request_logs (
    log_id            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT nn_request_logs_id NOT NULL,
    endpoint_id       NUMBER(10)    CONSTRAINT nn_request_logs_ep_id NOT NULL,
    source_ip         VARCHAR2(45)  DEFAULT '0.0.0.0' CONSTRAINT nn_request_logs_ip NOT NULL,
    body_length       NUMBER(10)    DEFAULT 0 CONSTRAINT nn_request_logs_body_len NOT NULL,
    http_status       NUMBER(3)     DEFAULT 200 CONSTRAINT nn_request_logs_status NOT NULL,
    logged_at         TIMESTAMP     DEFAULT SYSTIMESTAMP CONSTRAINT nn_request_logs_logged_at NOT NULL
) TABLESPACE apithreat_data;

-- 3. Child Table (1:1): REQUEST_LEXICAL_METRICS
CREATE TABLE request_lexical_metrics (
    metric_id           NUMBER(10) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT nn_lexical_metrics_id NOT NULL,
    log_id              NUMBER(10)  CONSTRAINT nn_lexical_metrics_log_id NOT NULL,
    url_single_q        NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_sq NOT NULL,
    url_double_q        NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_dq NOT NULL,
    url_dashes          NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_dash NOT NULL,
    url_braces          NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_brace NOT NULL,
    url_spaces          NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_space NOT NULL,
    url_percentages     NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_pct NOT NULL,
    url_semicolons      NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_semi NOT NULL,
    url_angle_brackets  NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_angle NOT NULL,
    url_special_chars   NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_spec NOT NULL,
    url_badwords        NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_url_badw NOT NULL,
    body_single_q       NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_sq NOT NULL,
    body_double_q       NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_dq NOT NULL,
    body_dashes         NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_dash NOT NULL,
    body_braces         NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_brace NOT NULL,
    body_spaces         NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_space NOT NULL,
    body_percentages    NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_pct NOT NULL,
    body_semicolons     NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_semi NOT NULL,
    body_angle_brackets NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_angle NOT NULL,
    body_special_chars  NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_spec NOT NULL,
    body_badwords       NUMBER(5)   DEFAULT 0 CONSTRAINT nn_lex_body_badw NOT NULL
) TABLESPACE apithreat_data;

-- 4. Child Table: SECURITY_THREATS
CREATE TABLE security_threats (
    threat_id         NUMBER(10) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT nn_security_threats_id NOT NULL,
    log_id            NUMBER(10)    CONSTRAINT nn_security_threats_log_id NOT NULL,
    threat_type       VARCHAR2(40)  DEFAULT 'ANOMALOUS_PAYLOAD' CONSTRAINT nn_security_threats_type NOT NULL,
    actual_class      NUMBER(1)     DEFAULT 0 CONSTRAINT nn_security_threats_class NOT NULL,
    model_prediction  NUMBER(1)     DEFAULT 0 CONSTRAINT nn_security_threats_pred NOT NULL,
    risk_score        NUMBER(3)     DEFAULT 0 CONSTRAINT nn_security_threats_score NOT NULL,
    detected_at       TIMESTAMP     DEFAULT SYSTIMESTAMP CONSTRAINT nn_security_threats_det_at NOT NULL
) TABLESPACE apithreat_data;

-- 5. Child Table: IP_QUARANTINE_LIST (threat_id is NULLABLE for ON DELETE SET NULL)
CREATE TABLE ip_quarantine_list (
    quarantine_id     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY CONSTRAINT nn_ip_quarantine_id NOT NULL,
    threat_id         NUMBER(10)    NULL,
    blocked_ip        VARCHAR2(45)  CONSTRAINT nn_ip_quarantine_ip NOT NULL,
    block_reason      VARCHAR2(255) CONSTRAINT nn_ip_quarantine_reason NOT NULL,
    is_active         CHAR(1)       DEFAULT 'Y' CONSTRAINT nn_ip_quarantine_active NOT NULL,
    quarantined_at    TIMESTAMP     DEFAULT SYSTIMESTAMP CONSTRAINT nn_ip_quarantine_at NOT NULL,
    expires_at        TIMESTAMP     NULL
) TABLESPACE apithreat_data;
